import { existsSync, mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { formatError, lintIcons, loadIcons } from './lint-icons.ts'
import type { IconNode } from './lib/svg.ts'
import { toPascalCase } from './lib/names.ts'

export type BuildOptions = { iconsDir: string; reactDir: string; svgDir: string }

const HEADER = '// Generated by tools/build-icons.ts – do not edit.'

const escapeAttr = (v: string) => v.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;')

function nodeToMarkup(node: IconNode): string {
  return node
    .map(([tag, attrs]) => {
      const list = Object.entries(attrs).map(([k, v]) => ` ${k}="${escapeAttr(v)}"`)
      return `<${tag}${list.join('')}/>`
    })
    .join('')
}

/** Replaces `dir` with exactly `files` (relative path -> content). */
function writeOwnedDir(dir: string, files: Map<string, string>): void {
  rmSync(dir, { recursive: true, force: true })
  mkdirSync(dir, { recursive: true })
  for (const [name, content] of files) writeFileSync(join(dir, name), content)
}

/**
 * Generates the React modules and the raw-SVG package from the icon sources.
 * Owns only `<reactDir>/icons/*`, `<reactDir>/index.ts` and, in `svgDir`,
 * `svg/`, `sprite.svg` and `icons.json`. Throws when the icons do not lint.
 */
export function buildIcons({ iconsDir, reactDir, svgDir }: BuildOptions): void {
  const present = existsSync(iconsDir)
  if (present) {
    const errors = lintIcons(iconsDir, { release: false })
    if (errors.length > 0) {
      throw new Error(`Refusing to build, ${errors.length} lint error(s):\n${errors.map(formatError).join('\n')}`)
    }
  }
  const icons = present ? loadIcons(iconsDir) : []

  const modules = new Map<string, string>()
  const svgs = new Map<string, string>()
  const exportLines: string[] = []
  const meta: Record<string, unknown> = {}
  const symbols: string[] = []

  for (const { name, svg, node, meta: m } of icons) {
    const pascal = toPascalCase(name)
    const doc = m.deprecated
      ? `/** @deprecated Since ${m.deprecated.since}${m.deprecated.replacement ? `; use ${toPascalCase(m.deprecated.replacement)}` : ''}. */\n`
      : ''
    modules.set(
      `${name}.ts`,
      `${HEADER}\nimport { createEvIcon } from '../create-ev-icon.js'\n\n${doc}export const ${pascal} = createEvIcon('${pascal}', '${name}', ${JSON.stringify(node)})\n\nexport default ${pascal}\n`,
    )
    exportLines.push(`export { ${pascal} } from './icons/${name}.js'`)
    for (const alias of m.aliases) exportLines.push(`export { ${pascal} as ${toPascalCase(alias)} } from './icons/${name}.js'`)

    svgs.set(`${name}.svg`, svg)
    meta[name] = { ...m, pascal }
    symbols.push(
      `  <symbol id="evicon-${name}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round">${nodeToMarkup(node)}</symbol>\n`,
    )
  }

  const index = [
    HEADER,
    "export { createEvIcon } from './create-ev-icon.js'",
    "export type * from './types.js'",
    ...exportLines.sort(),
  ].join('\n')

  mkdirSync(reactDir, { recursive: true })
  mkdirSync(svgDir, { recursive: true })
  writeOwnedDir(join(reactDir, 'icons'), modules)
  writeFileSync(join(reactDir, 'index.ts'), `${index}\n`)
  writeOwnedDir(join(svgDir, 'svg'), svgs)
  writeFileSync(join(svgDir, 'sprite.svg'), `<svg xmlns="http://www.w3.org/2000/svg">\n${symbols.join('')}</svg>\n`)
  writeFileSync(join(svgDir, 'icons.json'), `${JSON.stringify(meta, null, 2)}\n`)
}

if (import.meta.main) {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
  try {
    buildIcons({
      iconsDir: join(root, 'icons'),
      reactDir: join(root, 'packages/react/src'),
      svgDir: join(root, 'packages/svg'),
    })
    const count = existsSync(join(root, 'icons')) ? readdirSync(join(root, 'icons')).filter((f) => f.endsWith('.svg')).length : 0
    console.log(`✓ built ${count} icons`)
  } catch (err) {
    console.error((err as Error).message)
    process.exitCode = 1
  }
}
