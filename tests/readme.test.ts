import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { pathToFileURL } from 'node:url'
import { describe, expect, it } from 'vitest'
import { ocpiVersion } from '../tools/lib/ocpi.ts'

const icons = Object.keys(
  JSON.parse(readFileSync('packages/svg/icons.json', 'utf8')) as Record<string, unknown>,
)

describe.each(['README.md', 'packages/react/README.md'])('%s', (file) => {
  const text = readFileSync(file, 'utf8')
  it('lists every icon as a table cell', () => {
    const missing = icons.filter((name) => !text.includes(`| \`${name}\` |`))
    expect(missing).toEqual([])
  })
})

const osm = JSON.parse(readFileSync('packages/svg/osm.json', 'utf8')) as Record<string, string>
const pascal = Object.fromEntries(
  Object.entries(JSON.parse(readFileSync('packages/svg/icons.json', 'utf8')) as Record<string, { pascal: string }>).map(
    ([name, meta]) => [name, meta.pascal],
  ),
)

// The OpenStreetMap table is written by hand; it must list exactly the tags of osm.json (built from icons/*.json).
describe.each(['README.md', 'site/src/content/docs/07-openstreetmap.mdx'])('%s OpenStreetMap section', (file) => {
  const text = readFileSync(file, 'utf8')
  it('lists every osm.json tag with its icon and component, in osm.json order', () => {
    const rows = [...text.matchAll(/^\| `([^`]+)` \| `([^`]+)` \| `([^`]+)` \|$/gm)]
      .filter((m) => m[1]! in osm || /[:=]/.test(m[1]!)) // tag rows only, not the icon tables
      .map((m) => [m[1], m[2], m[3]])
    expect(rows).toEqual(Object.entries(osm).map(([tag, name]) => [tag, name, pascal[name]]))
  })
  it('maps the same sockets in the React example', () => {
    const entries = [...text.matchAll(/^ {2}'(socket:[a-z0-9_]+)': (\w+),$/gm)].map((m) => [m[1], m[2]])
    const sockets = Object.entries(osm).filter(([tag]) => tag.startsWith('socket:') && tag !== 'socket:unknown')
    expect(entries).toEqual(sockets.map(([tag, name]) => [tag, pascal[name]]))
  })
})

const ocpi = JSON.parse(readFileSync('packages/svg/ocpi.json', 'utf8')) as Record<string, string>

// The OCPI table is generated by hand like the OSM table; it must list exactly the values of ocpi.json, with the
// first OCPI version that defines each value (tools/lib/ocpi.ts).
describe.each(['README.md', 'site/src/content/docs/08-ocpi.mdx'])('%s OCPI section', (file) => {
  const text = readFileSync(file, 'utf8')
  it('lists every ocpi.json value with its icon, component and OCPI version, in ocpi.json order', () => {
    const rows = [...text.matchAll(/^\| `([^`]+)` \| `([^`]+)` \| `([^`]+)` \| (2\.2\.1|2\.3) \|$/gm)].map((m) => [m[1], m[2], m[3], m[4]])
    expect(rows).toEqual(
      Object.entries(ocpi).map(([value, name]) => [value, name, pascal[name], ocpiVersion(value) === '2.2.1' ? '2.2.1' : '2.3']),
    )
  })
  it('shows the real output of the example', async () => {
    const code = text.match(/^### Values to icons\n[\s\S]*?^```ts\n([\s\S]*?)^```$/m)![1]!
    const calls = [...code.matchAll(/^(ocpiIcons\(.*\)) \/\/ (\[.*\])$/gm)]
    expect(calls.length).toBeGreaterThanOrEqual(3)
    const module = code.replace(/^(ocpiIcons\(.*\)) \/\/ (\[.*\])$/gm, '').replace(/$/, `\nexport const results = [${calls.map((m) => `[${m[1]}, ${m[2]}]`).join(', ')}]\n`)
    mkdirSync('.tmp-tests', { recursive: true })
    const path = resolve(`.tmp-tests/ocpi-example-${file.replace(/\W/g, '-')}.ts`)
    writeFileSync(path, module)
    const { results } = (await import(pathToFileURL(path).href)) as { results: Array<[string[], string[]]> }
    for (const [actual, expected] of results) expect(actual).toEqual(expected)
  })
})

it('the README and the docs page carry the same OCPI section', () => {
  const readme = readFileSync('README.md', 'utf8').match(/^## OCPI\n\n([\s\S]*?)\n## /m)![1]!
  const docs = readFileSync('site/src/content/docs/08-ocpi.mdx', 'utf8').replace(/^---\n[\s\S]*?\n---\n\n/, '')
  expect(docs).toBe(readme)
})
