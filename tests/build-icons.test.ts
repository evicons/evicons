// @vitest-environment jsdom
import { copyFileSync, existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createElement } from 'react'
import { render } from '@testing-library/react'
import { afterEach, beforeEach, expect, test } from 'vitest'
import { buildIcons } from '../tools/build-icons.ts'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const VALID = join(ROOT, 'tests/fixtures/icons-valid')
const INVALID = join(ROOT, 'tests/fixtures/icons-invalid/foreign-attrs')
// Inside the repo (not os.tmpdir) so generated modules can resolve `react`.
const TMP_BASE = join(ROOT, '.tmp-tests')

let tmp: string
let reactDir: string
let svgDir: string

const opts = (iconsDir = VALID) => ({ iconsDir, reactDir, svgDir })
const read = (...p: string[]) => readFileSync(join(tmp, ...p), 'utf8')

beforeEach(() => {
  mkdirSync(TMP_BASE, { recursive: true })
  tmp = mkdtempSync(join(TMP_BASE, 'build-'))
  reactDir = join(tmp, 'react-src')
  svgDir = join(tmp, 'svg-pkg')
  mkdirSync(reactDir)
  mkdirSync(svgDir)
  for (const f of ['create-ev-icon.ts', 'types.ts']) copyFileSync(join(ROOT, 'packages/react/src', f), join(reactDir, f))
})
afterEach(() => rmSync(tmp, { recursive: true, force: true }))

test('writes one module per icon and an index', () => {
  buildIcons(opts())
  expect(existsSync(join(reactDir, 'icons/test-ring.ts'))).toBe(true)
  expect(existsSync(join(reactDir, 'icons/test-bolt.ts'))).toBe(true)
  expect(existsSync(join(svgDir, 'svg/test-ring.svg'))).toBe(true)
  expect(read('svg-pkg/svg/test-ring.svg')).toBe(readFileSync(join(VALID, 'test-ring.svg'), 'utf8'))
  const index = read('react-src/index.ts')
  expect(index).toContain("export { createEvIcon } from './create-ev-icon.js'")
  expect(index).toContain("export type * from './types.js'")
  expect(index).toContain("export { TestRing } from './icons/test-ring.js'")
  expect(index).toContain("export { TestBolt as TestFlash } from './icons/test-bolt.js'")
  const lines = index.split('\n').filter((l) => l.includes('./icons/'))
  expect(lines).toEqual([...lines].sort())
  expect(read('react-src/icons/test-bolt.ts')).toContain('@deprecated')
  expect(read('react-src/icons/test-ring.ts')).not.toContain('@deprecated')
  expect(read('react-src/icons/test-ring.ts')).toContain('// Generated by tools/build-icons.ts')
})

test('module renders', async () => {
  buildIcons(opts())
  const mod = await import(/* @vite-ignore */ join(reactDir, 'icons/test-ring.ts'))
  const { container } = render(createElement(mod.TestRing))
  expect(container.querySelector('circle')?.getAttribute('r')).toBe('9')
  expect(mod.default).toBe(mod.TestRing)
})

test('sprite has one symbol per icon', () => {
  buildIcons(opts())
  const sprite = read('svg-pkg/sprite.svg')
  expect(sprite).toContain('<svg xmlns="http://www.w3.org/2000/svg">')
  expect(sprite).toContain('id="evicon-test-ring"')
  expect(sprite).toContain('id="evicon-test-bolt"')
  expect(sprite).toContain('viewBox="0 0 24 24"')
  expect(sprite).toContain('stroke-width="1.5"')
  expect(sprite.match(/<symbol /g)).toHaveLength(2)
  expect(sprite).toContain('<circle cx="12" cy="12" r="9"/>')
})

test('icons.json carries meta + pascal', () => {
  buildIcons(opts())
  const json = JSON.parse(read('svg-pkg/icons.json'))
  expect(Object.keys(json)).toEqual(['test-bolt', 'test-ring'])
  expect(json['test-ring'].pascal).toBe('TestRing')
  expect(json['test-ring'].category).toBe('status')
  expect(json['test-bolt'].aliases).toEqual(['test-flash'])
  expect(read('svg-pkg/icons.json')).toContain('\n  "test-bolt": {')
})

test('removes stale outputs', () => {
  mkdirSync(join(reactDir, 'icons'))
  writeFileSync(join(reactDir, 'icons/old.ts'), 'x')
  mkdirSync(join(svgDir, 'svg'))
  writeFileSync(join(svgDir, 'svg/old.svg'), 'x')
  buildIcons(opts())
  expect(existsSync(join(reactDir, 'icons/old.ts'))).toBe(false)
  expect(existsSync(join(svgDir, 'svg/old.svg'))).toBe(false)
  expect(existsSync(join(reactDir, 'create-ev-icon.ts'))).toBe(true)
  expect(existsSync(join(reactDir, 'types.ts'))).toBe(true)
})

test('is deterministic', () => {
  const snapshot = () =>
    [reactDir, svgDir].flatMap((d) =>
      (readdirSync(d, { recursive: true }) as string[]).sort().map((f) => {
        try {
          return [f, readFileSync(join(d, f), 'utf8')]
        } catch {
          return [f, null]
        }
      }),
    )
  buildIcons(opts())
  const first = snapshot()
  buildIcons(opts())
  expect(snapshot()).toEqual(first)
})

test('builds zero icons from an empty or missing directory', () => {
  buildIcons(opts(join(tmp, 'missing')))
  expect(read('react-src/index.ts')).not.toContain('./icons/')
  expect(read('svg-pkg/icons.json')).toBe('{}\n')
  expect(read('svg-pkg/sprite.svg')).toContain('<svg xmlns="http://www.w3.org/2000/svg">')
  expect(readdirSync(join(reactDir, 'icons'))).toEqual([])
})

test('refuses to build when lint fails', () => {
  expect(() => buildIcons(opts(INVALID))).toThrow()
  expect(existsSync(join(reactDir, 'index.ts'))).toBe(false)
})

test('package LICENSE files are byte-identical copies of the root LICENSE', () => {
  const root = readFileSync(join(ROOT, 'LICENSE'))
  for (const pkg of ['react', 'svg']) {
    const file = join(ROOT, 'packages', pkg, 'LICENSE')
    expect(existsSync(file), `${file} is missing`).toBe(true)
    expect(readFileSync(file), `${file} differs from the root LICENSE`).toEqual(root)
  }
})

test('marker svg files are self-contained images', () => {
  const svgDir = join(ROOT, 'packages/svg/svg')
  const markers = readdirSync(svgDir).filter((f) => /^marker(-.*)?\.svg$/.test(f))
  expect(markers).toHaveLength(8)
  for (const file of markers) {
    const svg = readFileSync(join(svgDir, file), 'utf8')
    expect(svg, file).toContain('xmlns="http://www.w3.org/2000/svg"')
    expect(svg, file).toContain('width="24"')
    expect(svg, file).toContain('height="24"')
  }
  const icons = JSON.parse(readFileSync(join(ROOT, 'packages/svg/icons.json'), 'utf8')) as Record<string, { since: string }>
  expect(Object.keys(icons)).toHaveLength(43)
  for (const [name, meta] of Object.entries(icons)) expect(['0.1.0', '0.2.0'], name).toContain(meta.since)
})
